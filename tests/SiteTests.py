#!/usr/bin/env python3
"""Offline checks for CUB3's static website and its published asset references."""
import re
import unittest
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'site'


class Page(HTMLParser):
    def __init__(self, path):
        super().__init__(convert_charrefs=True)
        self.ids = []
        self.references = []
        self.images = []
        self.feed(path.read_text(encoding='utf-8'))

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if 'id' in attrs:
            self.ids.append(attrs['id'])
        if 'href' in attrs:
            self.references.append(attrs['href'])
        if 'src' in attrs:
            self.references.append(attrs['src'])
        if tag == 'img':
            self.images.append(attrs)


class SiteTests(unittest.TestCase):
    def setUp(self):
        self.pages = {p.name: Page(p) for p in SITE.glob('*.html')}

    def test_local_references_and_anchors(self):
        for name, page in self.pages.items():
            self.assertEqual(len(page.ids), len(set(page.ids)), name)
            for ref in page.references:
                url = urlsplit(ref)
                if url.scheme or url.netloc:
                    continue
                path = unquote(url.path)
                # Generated by the Pages build, not checked into the repository.
                generated_downloads = {
                    'downloads/cub3-launcher-dev-amd64.deb',
                    'downloads/cub3-launcher-windows-x64.zip',
                    'downloads/cub3-launcher-windows-x64.zip.sha256',
                }
                if path in generated_downloads and not (SITE / path).is_file():
                    self.assertFalse(url.fragment)
                    continue
                target = (SITE / name).parent / path if path else SITE / name
                with self.subTest(page=name, reference=ref):
                    self.assertTrue(target.is_file(), f'Missing local file: {target}')
                    if url.fragment and target.suffix == '.html':
                        self.assertIn(url.fragment, Page(target).ids)

    def test_images_have_alternative_text_and_logos_are_real_assets(self):
        for name, page in self.pages.items():
            for img in page.images:
                self.assertIn('alt', img, f'{name}: {img}')
                if img['src'].endswith('.svg'):
                    ET.parse(SITE / img['src'])
        index = (SITE / 'index.html').read_text(encoding='utf-8')
        policy = (SITE / 'politica.html').read_text(encoding='utf-8')
        for platform in ('linux', 'windows', 'macos'):
            self.assertIn(f'assets/platforms/{platform}.png', index)
        for page in (index, policy):
            self.assertIn('assets/logos/cub3-logo-01-island.svg', page)

    def test_changelog_and_legacy_anchors(self):
        page = self.pages['index.html']
        for anchor in ('inicio', 'caracteristicas', 'mods', 'fixes', 'descargas', 'guia', 'identidad'):
            self.assertIn(anchor, page.ids)
        content = (SITE / 'index.html').read_text(encoding='utf-8')
        self.assertEqual(len(re.findall(r'class="fix-number"', content)), 16)

    def test_layout_regressions(self):
        css = (SITE / 'styles.css').read_text(encoding='utf-8')
        self.assertEqual(css.count('{'), css.count('}'))
        # Absolutely positioned hero image must fill its relatively positioned frame.
        self.assertRegex(css, r'\.hero-image-wrap img\s*\{[^}]*position:absolute;[^}]*inset:0')
        self.assertIn('id="caracteristicas"', (SITE / 'index.html').read_text(encoding='utf-8'))
        self.assertRegex(css, r'\.download-name\s*\{[^}]*min-width:0')
        self.assertIn('@media(max-width:360px)', css)

    def test_theme_switch_and_motion_accessibility(self):
        for name in ('index.html', 'politica.html'):
            content = (SITE / name).read_text(encoding='utf-8')
            self.assertIn("localStorage.getItem('cub3-site-theme')", content)
            self.assertIn("localStorage.setItem('cub3-site-theme', next)", content)
            self.assertIn('aria-pressed="false"', content)
        css = (SITE / 'styles.css').read_text(encoding='utf-8')
        self.assertIn(':root[data-theme="dark"]', css)
        self.assertIn('@keyframes rise-in', css)
        self.assertIn('@keyframes drift', css)
        self.assertIn('prefers-reduced-motion:reduce', css)
        self.assertIn('backdrop-filter:blur(18px)', css)

    def test_contributions_are_pull_request_only(self):
        index = (SITE / 'index.html').read_text(encoding='utf-8')
        contributing = (ROOT / 'CONTRIBUTING.md').read_text(encoding='utf-8')
        readme = (ROOT / 'README.md').read_text(encoding='utf-8')
        self.assertIn('Todos los cambios se envían mediante pull request a', index)
        self.assertIn('no se aceptan contribuciones con push directo', index.lower())
        self.assertIn('CONTRIBUTING.md', index)
        self.assertIn('no se aceptan contribuciones mediante', contributing)
        self.assertIn('No se aceptan pushes ni commits directos', readme)

    def test_windows_zip_is_published_only_from_the_matching_successful_ci_artifact(self):
        index = (SITE / 'index.html').read_text(encoding='utf-8')
        self.assertIn('href="downloads/cub3-launcher-windows-x64.zip"', index)
        self.assertIn('href="downloads/cub3-launcher-windows-x64.zip.sha256"', index)
        self.assertIn('aria-label="Descargar el ZIP portable experimental de CUB3 Launcher para Windows x64"', index)
        self.assertIn('CI VERDE · EXPERIMENTAL', index)
        self.assertIn('El proyecto mantiene CI para Linux y Windows.', index)
        self.assertIn('El ZIP de Windows se publica aquí tras pasar el CI de Linux y Windows', index)
        self.assertIn('CI compila y prueba Windows', index)

        workflow = (ROOT / '.github/workflows/pages.yml').read_text(encoding='utf-8')
        self.assertIn('workflow_run:', workflow)
        self.assertIn('workflows: ["Build and test"]', workflow)
        self.assertIn("if: github.event.workflow_run.event == 'push' && github.event.workflow_run.conclusion == 'success'", workflow)
        self.assertIn('actions/download-artifact@v4', workflow)
        self.assertIn('run-id: ${{ github.event.workflow_run.id }}', workflow)
        self.assertIn('github.event.workflow_run.head_sha', workflow)
        self.assertIn('stage_windows_bundle.py windows-artifact site/downloads', workflow)
        verifier = (ROOT / 'scripts/stage_windows_bundle.py').read_text(encoding='utf-8')
        self.assertIn('failed SHA-256 verification', verifier)
        self.assertIn('ZipFile(archive)', verifier)
        self.assertIn('cub3-launcher-windows-x64.zip.sha256', workflow)
        self.assertIn('actions: read', workflow)

    def test_windows_checkout_has_parent_for_diff_check(self):
        workflow = (ROOT / '.github/workflows/build.yml').read_text(encoding='utf-8')
        windows = workflow.split('  windows-release:', 1)[1]
        self.assertRegex(windows, r'Checkout CUB3\n\s+uses: actions/checkout@v4\n\s+with:\n\s+fetch-depth: 0')
        self.assertIn('git diff --check HEAD^ HEAD', windows)


if __name__ == '__main__':
    unittest.main()
